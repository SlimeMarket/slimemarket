// translate: tr(key, fallback) → string in current lang, fallback to EN, then fallback text
function tr(key, fallback) {
  const lang = __LANG;
  if (lang !== 'en' && DICT[lang] && DICT[lang][key]) return DICT[lang][key];
  if (DICT.en[key]) return DICT.en[key];
  if (fallback != null) return fallback;
  return key;
}

// hook so components re-render on language change
function useLang() {
  const [, force] = useStateI18n(0);
  useEffectI18n(() => {
    const h = () => force(n => n + 1);
    window.addEventListener('slime-lang', h);
    return () => window.removeEventListener('slime-lang', h);
  }, []);
  return __LANG;
}

// compact ENG | ID | 中 | RU switcher for topbar
function LangSwitcher() {
  const cur = useLang();
  return (
    <div className="flex items-center rounded-xl bg-arc-surface/60 ring-1 ring-arc-border p-0.5">
      {LANGS.map(l => (
        <button key={l.id} onClick={() => setLang(l.id)} title={l.name}
          className={`min-w-[34px] h-9 px-2 rounded-lg text-xs font-semibold transition ${cur === l.id ? 'bg-arc-primary text-white shadow-glow' : 'text-arc-muted hover:text-arc-text'}`}>
          {l.short}
        </button>
      ))}
    </div>
  );
}

Object.assign(window, { LANGS, getLang, setLang, tr, useLang, LangSwitcher, DICT });
