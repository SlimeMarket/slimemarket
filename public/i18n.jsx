let __LANG = (() => { try { return localStorage.getItem('slime_lang') || 'en'; } catch (e) { return 'en'; } })();
const getLang = () => __LANG;
const setLang = (l) => {
  __LANG = l;
  try { localStorage.setItem('slime_lang', l); } catch (e) {}
  document.documentElement.setAttribute('lang', l);
  window.dispatchEvent(new CustomEvent('slime-lang', { detail: l }));

  // Persist the choice server-side.
  //
  // Before this, the language lived ONLY in localStorage: switching device
  // silently reset it to English, and `ME.preferred_lang` stayed 'en' forever —
  // which is what public/ucw-helper.jsx reads to localize Circle's hosted PIN
  // UI, so that always came up in English too.
  //
  // Fire-and-forget on purpose: a failed write must never block the switch, and
  // the local value is already applied. Mirrored onto ME so anything reading
  // ME.preferred_lang this session (ucw-helper) sees the new value immediately.
  if (window.ME && window.ME.id) {
    window.ME.preferred_lang = l;
    try {
      fetch((window.SLIME_API || '') + '/api/me', {
        method: 'PATCH',
        headers: { 'Content-Type': 'application/json' },
        credentials: 'same-origin',
        body: JSON.stringify({ preferred_lang: l }),
      }).catch(() => {});
    } catch (e) { /* offline / blocked — localStorage still holds it */ }
  }
};

