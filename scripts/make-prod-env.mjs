#!/usr/bin/env node
/**
 * Generate `.env.production` from `.env.local` + production overrides.
 *
 * WHY: `.env.production` is gitignored, so it never exists in a fresh clone and
 * has to be assembled by hand from `.env.example` — which is exactly
 * where the "wrong domain / mock mode still on / Turnstile half-configured"
 * class of launch bugs comes from. This copies the values that are IDENTICAL
 * between local and production (Circle testnet keys, SMTP mailbox, escrow
 * contract, Upstash) and forces the values that MUST differ.
 *
 * Usage:
 *   node scripts/make-prod-env.mjs                       # domain default below
 *   node scripts/make-prod-env.mjs https://other.com
 *
 * It never prints secret values — only the keys it filled and the keys that
 * still need a human (Supabase Cloud project).
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const APP_URL = process.argv[2] || "https://slimemarket.app";

if (!existsSync(".env.local")) {
  console.error(".env.local not found — run this from the repo root.");
  process.exit(1);
}

/** Minimal .env parser preserving order + comments. */
function parseEnv(text) {
  const out = [];
  for (const line of text.split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=(.*)$/);
    out.push(m ? { key: m[1], value: m[2], raw: line } : { key: null, raw: line });
  }
  return out;
}

const local = parseEnv(readFileSync(".env.local", "utf8"));
const byKey = new Map(local.filter((l) => l.key).map((l) => [l.key, l.value]));

/** Values that MUST be overridden for production. */
const OVERRIDES = {
  NODE_ENV: "production",
  NEXT_PUBLIC_APP_URL: APP_URL,
  CIRCLE_PAYMENTS_MOCK: "0",
  FORCE_REAL_UCW: "true",
  ONCHAIN_WALLET_FUNDS: "1",
  // Turnstile stays OFF until explicitly enabled (see .env.example).
  TURNSTILE_ENABLED: "false",
};

/** Keys that only exist in production and must be filled by a human. */
const NEEDS_HUMAN = [
  "NEXT_PUBLIC_SUPABASE_URL",
  "NEXT_PUBLIC_SUPABASE_PUBLISHABLE_OR_ANON_KEY",
  "SUPABASE_SECRET_KEY",
  "SUPABASE_SERVICE_ROLE_KEY",
];

const lines = [];
lines.push("# ============================================================================");
lines.push("# .env.production — GENERATED by scripts/make-prod-env.mjs");
lines.push("# Regenerate after changing .env.local:  node scripts/make-prod-env.mjs");
lines.push(`# App URL: ${APP_URL}`);
lines.push("#");
lines.push("# GITIGNORED. Never commit. Fill the Supabase Cloud values marked TODO.");
lines.push("# ============================================================================");
lines.push("");

const seen = new Set();
for (const entry of local) {
  if (!entry.key) {
    lines.push(entry.raw);
    continue;
  }
  if (seen.has(entry.key)) continue;
  seen.add(entry.key);

  if (entry.key in OVERRIDES) {
    lines.push(`${entry.key}=${OVERRIDES[entry.key]}`);
    continue;
  }
  if (NEEDS_HUMAN.includes(entry.key)) {
    lines.push(`${entry.key}=            # TODO: Supabase Cloud value`);
    continue;
  }
  lines.push(entry.raw);
}

// Keys that production needs but .env.local never had.
for (const [k, v] of Object.entries(OVERRIDES)) {
  if (!seen.has(k)) lines.push(`${k}=${v}`);
}
for (const k of NEEDS_HUMAN) {
  if (!seen.has(k)) lines.push(`${k}=            # TODO: Supabase Cloud value`);
}

writeFileSync(".env.production", lines.join("\n") + "\n", "utf8");

console.log(`\n✓ .env.production written (app URL: ${APP_URL})\n`);
console.log("Overridden for production:");
for (const [k, v] of Object.entries(OVERRIDES)) console.log(`  ${k}=${v}`);
console.log("\nCopied from .env.local (values not shown):");
for (const k of ["CIRCLE_API_KEY", "CIRCLE_ENTITY_SECRET", "CIRCLE_APP_ID", "PLATFORM_CIRCLE_WALLET_ID",
  "ESCROW_CONTRACT_ADDRESS", "UPSTASH_REDIS_REST_URL", "SMTP_HOST", "SMTP_USER", "SMTP_FROM"]) {
  if (byKey.has(k) && byKey.get(k).trim()) console.log(`  ${k}`);
}
console.log("\n⚠ STILL NEEDS A HUMAN (Supabase Cloud project):");
for (const k of NEEDS_HUMAN) console.log(`  ${k}`);
console.log("");
